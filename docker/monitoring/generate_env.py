"""Generate the Grafana admin password (random, local, git-ignored).

    python docker/monitoring/generate_env.py                    # creates docker/monitoring/.env
    python docker/monitoring/generate_env.py --print-password

Grafana ships with a well-known default login, so the compose service refuses to start without
this file instead of falling back to it. The value is random, written owner-read-only where the
platform supports it, and never committed. An existing file is not overwritten (``--force``
replaces it). Standard library only.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent / ".env"
KEY = "GF_SECURITY_ADMIN_PASSWORD"  # the variable Grafana itself reads


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docker/monitoring/.env")
    parser.add_argument("--force", action="store_true", help="replace an existing file")
    parser.add_argument("--print-password", action="store_true", help="show the password")
    parser.add_argument("--path", type=Path, default=TARGET, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.path.exists() and not args.force:
        print(f"{args.path} already exists; not overwriting (use --force to replace).")
        if args.print_password:
            for line in args.path.read_text(encoding="utf-8").splitlines():
                if line.startswith(f"{KEY}="):
                    print(line)
        return 0

    password = secrets.token_urlsafe(18)
    args.path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(args.path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(
            "# Generated by docker/monitoring/generate_env.py. Random, local, never commit.\n"
        )
        handle.write(f"{KEY}={password}\n")
    print(f"wrote {args.path}")
    print("Grafana user: admin")
    print(
        f"Grafana password: {password}"
        if args.print_password
        else "Password: see the file, or rerun with --print-password"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
