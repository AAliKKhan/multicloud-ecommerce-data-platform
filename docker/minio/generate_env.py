"""Generate the secrets for the local MinIO stand-in (random, local, git-ignored).

    python docker/minio/generate_env.py
    python docker/minio/generate_env.py --print-login

Two files, so the powerful MinIO root credentials never reach the pipeline:

* ``.env.root``: the MinIO root user and password (read by the MinIO server and the init job only).
* ``.env``: the bucket name, the endpoint, and the **pipeline user** access key and secret. This is
  what the pipeline commands and the Spark container read (see ``ecomm.lake.stores``). That user
  can only do what the Terraform pipeline role may do on S3.

Existing files are not overwritten (``--force`` replaces both). Standard library only.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUCKET = "ecomm-raw-minio"
ENDPOINT = "http://127.0.0.1:9000"


def _write_private(path: Path, header: str, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"# {header}\n")
        for key, value in values.items():
            handle.write(f"{key}={value}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docker/minio/.env and .env.root")
    parser.add_argument("--force", action="store_true", help="replace existing files")
    parser.add_argument("--print-login", action="store_true", help="show the pipeline credentials")
    parser.add_argument("--dir", type=Path, default=HERE, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    app_env = args.dir / ".env"
    root_env = args.dir / ".env.root"
    if (app_env.exists() or root_env.exists()) and not args.force:
        print("MinIO secret files already exist; not overwriting (use --force to replace).")
        if args.print_login and app_env.exists():
            for line in app_env.read_text(encoding="utf-8").splitlines():
                if line.startswith(("ECOMM_S3_ACCESS_KEY=", "ECOMM_S3_SECRET_KEY=")):
                    print(line)
        return 0

    _write_private(
        root_env,
        "Generated by docker/minio/generate_env.py. MinIO server and init job only. Never commit.",
        {
            "MINIO_ROOT_USER": "root-" + secrets.token_hex(4),
            "MINIO_ROOT_PASSWORD": secrets.token_urlsafe(24),
        },
    )
    access_key = "pipeline-" + secrets.token_hex(4)
    secret_key = secrets.token_urlsafe(24)
    _write_private(
        app_env,
        "Generated by docker/minio/generate_env.py. Random, local, never commit.",
        {
            "ECOMM_S3_BUCKET": BUCKET,
            "ECOMM_S3_ENDPOINT_URL": ENDPOINT,
            "ECOMM_S3_ACCESS_KEY": access_key,
            "ECOMM_S3_SECRET_KEY": secret_key,
        },
    )
    print(f"wrote {app_env}\nwrote {root_env}")
    print(f"Bucket: {BUCKET}   Pipeline user: {access_key}")
    print(
        f"Pipeline secret: {secret_key}"
        if args.print_login
        else "Secret: see docker/minio/.env, or rerun with --print-login"
    )
    print("Select it with: set ECOMM_S3_BACKEND=minio   (default stays the local directory)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
