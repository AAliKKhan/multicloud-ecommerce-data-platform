"""Generate the secrets for the BI stack (random, local, git-ignored).

    python docker/bi/generate_env.py     # creates docker/bi/.env and docker/bi/.env.postgres
    python docker/bi/generate_env.py --print-login

Two files, so the Postgres superuser password is only ever given to the Postgres container:

* ``.env.postgres``: the superuser password (read by the Postgres container only).
* ``.env``: the three application role passwords, the Metabase admin login, and
  ``MB_DB_PASS`` (the name Metabase itself reads). Read by Metabase, by Postgres (to create the
  roles) and by the host tools.

Existing files are not overwritten (``--force`` replaces both). Standard library only.
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP_ENV = HERE / ".env"
POSTGRES_ENV = HERE / ".env.postgres"
ADMIN_EMAIL = "admin@ecomm.local"


def admin_password() -> str:
    """A random password that satisfies Metabase's complexity policy.

    Metabase rejects passwords without a mix of lower case, upper case, digits and a symbol (it
    reports "too common"), so draw until all four kinds are present. Still fully random.
    """
    while True:
        candidate = secrets.token_urlsafe(18)
        if (
            any(c.islower() for c in candidate)
            and any(c.isupper() for c in candidate)
            and sum(c.isdigit() for c in candidate) >= 2
            and any(c in "-_" for c in candidate)
        ):
            return candidate


def _write_private(path: Path, header: str, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"# {header}\n")
        for key, value in values.items():
            handle.write(f"{key}={value}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docker/bi/.env and .env.postgres")
    parser.add_argument("--force", action="store_true", help="replace existing files")
    parser.add_argument("--print-login", action="store_true", help="show the Metabase login")
    parser.add_argument("--dir", type=Path, default=HERE, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    app_env = args.dir / ".env"
    postgres_env = args.dir / ".env.postgres"
    if (app_env.exists() or postgres_env.exists()) and not args.force:
        print("BI secret files already exist; not overwriting (use --force to replace).")
        if args.print_login and app_env.exists():
            for line in app_env.read_text(encoding="utf-8").splitlines():
                if line.startswith(("METABASE_ADMIN_EMAIL=", "METABASE_ADMIN_PASSWORD=")):
                    print(line)
        return 0

    metabase_db_password = secrets.token_urlsafe(18)
    metabase_admin_password = admin_password()
    _write_private(
        postgres_env,
        "Generated by docker/bi/generate_env.py. Postgres container only. Never commit.",
        {"POSTGRES_PASSWORD": secrets.token_urlsafe(24)},
    )
    _write_private(
        app_env,
        "Generated by docker/bi/generate_env.py. Random, local, never commit.",
        {
            "METABASE_DB_PASSWORD": metabase_db_password,
            "MB_DB_PASS": metabase_db_password,
            "BI_PUBLISHER_PASSWORD": secrets.token_urlsafe(18),
            "BI_READER_PASSWORD": secrets.token_urlsafe(18),
            "METABASE_ADMIN_EMAIL": ADMIN_EMAIL,
            "METABASE_ADMIN_PASSWORD": metabase_admin_password,
        },
    )
    print(f"wrote {app_env}\nwrote {postgres_env}")
    print(f"Metabase user: {ADMIN_EMAIL}")
    print(
        f"Metabase password: {metabase_admin_password}"
        if args.print_login
        else "Password: see docker/bi/.env, or rerun with --print-login"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
