"""Generate the Airflow secrets file (random, local, git-ignored).

    python docker/airflow/generate_env.py            # creates docker/airflow/.env
    python docker/airflow/generate_env.py --print-password

Nothing here is a default or a shared secret: every value is freshly random. The file is read by
docker compose (``env_file``) for the Airflow and Postgres containers only. It is refused if it
already exists (so a running installation keeps its database password); pass ``--force`` to
replace it, which also requires deleting the Postgres volume (``docker compose down -v``).

Standard library only, so it runs before anything is installed.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent / ".env"
DB_USER = "airflow"
DB_NAME = "airflow"
DB_HOST = "airflow-postgres"


def new_values() -> dict[str, str]:
    """Fresh random settings. The database password is URL-safe (it sits inside a URL)."""
    db_password = secrets.token_urlsafe(24)
    return {
        "POSTGRES_USER": DB_USER,
        "POSTGRES_DB": DB_NAME,
        "POSTGRES_PASSWORD": db_password,
        "AIRFLOW__DATABASE__SQL_ALCHEMY_CONN": (
            f"postgresql+psycopg2://{DB_USER}:{db_password}@{DB_HOST}:5432/{DB_NAME}"
        ),
        # A Fernet key is 32 random bytes, URL-safe base64 encoded.
        "AIRFLOW__CORE__FERNET_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
        "AIRFLOW__WEBSERVER__SECRET_KEY": secrets.token_hex(32),
        "AIRFLOW_ADMIN_PASSWORD": secrets.token_urlsafe(16),
    }


def render(values: dict[str, str]) -> str:
    header = (
        "# Generated by docker/airflow/generate_env.py. Random, local, never commit.\n"
        "# Delete this file together with the Postgres volume to start over.\n"
    )
    return header + "".join(f"{key}={value}\n" for key, value in values.items())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docker/airflow/.env")
    parser.add_argument("--force", action="store_true", help="replace an existing file")
    parser.add_argument("--print-password", action="store_true", help="show the admin password")
    parser.add_argument("--path", type=Path, default=TARGET, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.path.exists() and not args.force:
        print(f"{args.path} already exists; not overwriting (use --force to replace).")
        if args.print_password:
            for line in args.path.read_text(encoding="utf-8").splitlines():
                if line.startswith("AIRFLOW_ADMIN_PASSWORD="):
                    print(line)
        return 0

    values = new_values()
    args.path.parent.mkdir(parents=True, exist_ok=True)
    # Created owner-read/write only where the platform supports POSIX permissions.
    fd = os.open(args.path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(values))
    print(f"wrote {args.path}")
    print("Airflow UI user: admin")
    if args.print_password:
        print(f"Airflow UI password: {values['AIRFLOW_ADMIN_PASSWORD']}")
    else:
        print(
            "Password: run again with --print-password, or read AIRFLOW_ADMIN_PASSWORD in the file."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
